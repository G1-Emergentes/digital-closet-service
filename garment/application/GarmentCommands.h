#pragma once
#include "../domain/repositories/GarmentRepository.h"
namespace mirage::garment
{
// Commands change state.
struct CreateGarmentCommand
{
    GarmentAccess access;
    std::string id; // generated by the interface layer
    GarmentDetails details;
};
struct UpdateGarmentCommand
{
    GarmentAccess access;
    std::string id;
    GarmentDetails details;
};
struct DeleteGarmentCommand
{
    GarmentAccess access;
    std::string id;
};
// Registers an image the client already uploaded to private Storage.
struct SetGarmentImageCommand
{
    GarmentAccess access;
    std::string id, imageId;
};
// Queries only read.
struct GetGarmentQuery
{
    GarmentAccess access;
    std::string id;
};
struct ListGarmentsQuery
{
    GarmentAccess access;
    int limit = 50;
    std::optional<std::string> cursor;
};
struct ResolveGarmentsQuery
{
    GarmentAccess access;
    std::vector<std::string> ids;
};
struct GarmentImageAccessQuery
{
    GarmentAccess access;
    std::string id;
};
} // namespace mirage::garment
